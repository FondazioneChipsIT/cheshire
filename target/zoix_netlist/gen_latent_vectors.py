#!/usr/bin/env python3
"""Generate the latent-error vectors of strobe_netlist.sv from the gate-level netlist.

At gate level the structures checked by the latent checks (register files,
scoreboard, CSRs, TLBs, branch predictor) are thousands of separate flops. For each
entry of the config file, this script:
  1. follows the instance path from the top module down to the instance,
  2. collects the output net (Q, or QN) of every flop whose instance name matches
     the given regular expression,
  3. writes one SystemVerilog vector with all of them.

The bit order does not matter: $fs_compare only checks whether the faulty machine
differs from the good machine anywhere in the vector.

Config file: one entry per line, whitespace separated, '#' starts a comment:
    <vector name>  <instance path relative to the DUT>  <regex on flop instance names>

Usage (rerun after every synthesis, since flop and net names can change):
    python3 gen_latent_vectors.py --netlist cheshire_wrap.v --config latent_vectors.cfg \
        > strobe_netlist_latent.svh
"""
import argparse
import re
import sys

MODULE_RE = re.compile(r'^\s*module\s+(\w+)\b')
ENDMODULE_RE = re.compile(r'^\s*endmodule\b')
# A cell or module instance: <type> <instance> ( <connections> );
CELL_RE = re.compile(r'^\s*(\w+)\s+(\w+)\s*\((.*?)\)\s*;', re.S | re.M)


def index_modules(path):
    """Return {module name: module text} for every module of the netlist."""
    modules, name, buf = {}, None, []
    with open(path) as f:
        for line in f:
            if name is None:
                m = MODULE_RE.match(line)
                if m:
                    name, buf = m.group(1), [line]
            else:
                buf.append(line)
                if ENDMODULE_RE.match(line):
                    modules[name] = ''.join(buf)
                    name = None
    return modules


def instance_type(text, inst):
    m = re.search(r'^\s*(\w+)\s+' + re.escape(inst) + r'\s*\(', text, re.M)
    return m.group(1) if m else None


def resolve(modules, top, relpath):
    """Follow relpath (dot-separated instance names) from top; return the module name."""
    mod = top
    for inst in relpath.split('.'):
        cell = instance_type(modules[mod], inst)
        if cell is None:
            raise LookupError(f"instance '{inst}' not found in module '{mod}'")
        if cell not in modules:
            raise LookupError(f"'{inst}' in '{mod}' is a library cell ({cell}), not a module")
        mod = cell
    return mod


def flop_outputs(text, regex, pins):
    """Output nets of the cells whose instance name fully matches regex."""
    rx = re.compile(regex)
    nets = []
    for m in CELL_RE.finditer(text):
        _, inst, conns = m.groups()
        if not rx.fullmatch(inst):
            continue
        for pin in pins:
            p = re.search(r'\.' + pin + r'\s*\(\s*([^()]*?)\s*\)', conns)
            if p and p.group(1) and not p.group(1).startswith('SYNOPSYS_UNCONNECTED'):
                nets.append(p.group(1))
                break
    return nets


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--netlist', required=True)
    ap.add_argument('--config', required=True)
    ap.add_argument('--top', default='cheshire_wrap', help='netlist top module (default: cheshire_wrap)')
    ap.add_argument('--dut', default='tb_cheshire_wrap.fix.dut',
                    help='hierarchical path of the top module in the testbench')
    ap.add_argument('--pins', default='Q,QN', help='flop output pins to try, in order')
    a = ap.parse_args()
    pins = a.pins.split(',')

    print(f'Indexing modules of {a.netlist} ...', file=sys.stderr)
    modules = index_modules(a.netlist)
    if a.top not in modules:
        sys.exit(f"top module '{a.top}' not found in {a.netlist}")

    print('// strobe_netlist_latent.svh: generated by gen_latent_vectors.py, do not edit.')
    print(f'// netlist: {a.netlist}, config: {a.config}')
    print()

    failures = 0
    with open(a.config) as cfg:
        for lineno, raw in enumerate(cfg, 1):
            line = raw.split('#', 1)[0].strip()
            if not line:
                continue
            try:
                name, relpath, regex = line.split()
            except ValueError:
                sys.exit(f'{a.config}:{lineno}: expected 3 fields, got: {line}')
            try:
                module = resolve(modules, a.top, relpath)
            except LookupError as e:
                print(f'ERROR {name}: {e}', file=sys.stderr)
                failures += 1
                continue
            nets = flop_outputs(modules[module], regex, pins)
            if not nets:
                print(f"ERROR {name}: no flop matching '{regex}' in module {module}", file=sys.stderr)
                failures += 1
                continue
            path = f'{a.dut}.{relpath}'
            print(f'// {name}: {len(nets)} flops of {module} matching /{regex}/')
            print(f'logic [{len(nets) - 1}:0] {name};')
            print(f'assign {name} = {{')
            print(',\n'.join(f'  {path}.{n}' for n in nets))
            print('};')
            print()
            print(f'{name:16s} {len(nets):7d} flops  ({module})', file=sys.stderr)

    if failures:
        sys.exit(f'{failures} entr{"y" if failures == 1 else "ies"} failed: fix the paths or regexes in {a.config}')


if __name__ == '__main__':
    main()
